const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = process.argv[2];
const { selectFrame } = require(path.join(root,'src/motion.cjs'));
const { currentAsset } = require(path.join(root,'src/page.cjs'));
assert.equal(currentAsset(1,['a','b','c'],{}),'c');
assert.equal(currentAsset(1,[],{}),'placeholder');
assert.equal(currentAsset(0.9,['a','b','c'],{reducedMotion:true}),'a');
assert.equal(currentAsset(0.9,['a','b','c'],{visible:false}),'a');
for (const [progress,expected] of [[-1,0],[0,0],[0.5,2],[1,4],[2,4],[NaN,0],[Infinity,0],['1',0]]) assert.equal(selectFrame(progress,5),expected);
for (const count of [0,-1,2.5,'5',null,NaN]) assert.equal(selectFrame(0.5,count),null);
assert.equal(selectFrame(1,1),0);
const tests = fs.readdirSync(path.join(root,'tests')).filter((name)=>name.endsWith('.test.cjs'));
assert.ok(tests.length > 0);
const result = spawnSync(process.execPath,['--test','--test-reporter=tap',...tests.map((name)=>path.join(root,'tests',name))],{encoding:'utf8',timeout:10000});
assert.equal(result.status,0,result.stdout+result.stderr);
assert.match(result.stdout,/# tests [1-9]/);
assert.match(result.stdout,/# skipped 0/);
console.log('reduced motion, clamping and real asset caller passed');
