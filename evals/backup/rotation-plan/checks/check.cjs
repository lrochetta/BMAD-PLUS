const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const { spawnSync } = require('node:child_process');
const root = process.argv[2];
const { deletionCandidates } = require(path.join(root, 'src/rotation.cjs'));
const { plan } = require(path.join(root, 'src/caller.cjs'));
const entry = (name, day, rest = {}) => ({path:name,created:`2026-09-${String(day).padStart(2,'0')}T00:00:00.000Z`,owned:true,verified:true,...rest});
const items = [entry('b3.zip',3), entry('b1.zip',1), entry('unknown.zip',4,{owned:false}), entry('b2.zip',2), entry('corrupt.zip',5,{verified:false}), entry('../escape.zip',1), entry('C:drive.zip',1), entry('dir\\x.zip',1), entry('bad.zip',1,{created:'yesterday'})];
const before = JSON.stringify(items);
assert.deepEqual(plan(items, 2), {delete:['b1.zip'],executed:false});
assert.equal(JSON.stringify(items), before);
assert.deepEqual(deletionCandidates([], 1), []);
assert.deepEqual(deletionCandidates([entry('a.zip',1),entry('a.zip',2),entry('z.zip',3)],1), []);
assert.deepEqual(deletionCandidates([entry('b.zip',1),entry('a.zip',1)],1), ['a.zip']);
assert.deepEqual(deletionCandidates([entry('bad.zip',1,{created:'2026-02-31T00:00:00.000Z'}),entry('good.zip',2)],1), []);
for (const keep of [0,-1,1.5,'2',null,NaN]) assert.throws(() => deletionCandidates(items,keep), TypeError);
const tests = fs.readdirSync(path.join(root,'tests')).filter((name)=>name.endsWith('.test.cjs'));
assert.ok(tests.length > 0);
const result = spawnSync(process.execPath,['--test','--test-reporter=tap',...tests.map((name)=>path.join(root,'tests',name))],{encoding:'utf8',timeout:10000});
assert.equal(result.status,0,result.stdout+result.stderr);
assert.match(result.stdout,/# tests [1-9]/);
assert.match(result.stdout,/# skipped 0/);
console.log('owned verified rotation, duplicate and invalid-path behavior passed');
